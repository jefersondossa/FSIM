//------------------------------------------------------------------------------
//-------------------------------CLEAR VARIABLES--------------------------------
//------------------------------------------------------------------------------
void Node::clearVariables(){
    pressure_ = 0.;   
    elemCorresp = 0;    
    weightFunction_ = 0.;

    for (int i = 0; i < 3; ++i){
        if (constrainType[i] != 1){
            velocity_[i] = 0.;   
            previousVelocity_[i] = 0.;   
            acceleration_[i] = 0.;
            previousAcceleration_[i] = 0.;
        }
        lagMultiplier_[i] = 0.;
        xsiCorresp[i] = 0.;
    }
    
    return;
}; 
