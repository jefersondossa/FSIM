//------------------------------------------------------------------------------
//-----------COMPUTES THE VALUE INTERPOLATED IN THE INTEGRATION POINT-----------
//------------------------------------------------------------------------------
double IntegQuadratureSpecial::interpolateQuadraticVariable(VecDouble &nValues, int point, int DIM) const {
    
    VecDouble xsi(DIM);
    double int_value = 0.;
    VecDouble phi_(nValues.size());

    for (int i=0; i<DIM; i++) xsi[i] = PointList(point,i);
    ShapeFunction shapeQuad(DIM,fOrder);
    shapeQuad.evaluate(xsi,phi_);
    
    for (int i = 0; i < nValues.size(); i++) int_value += nValues[i] * phi_[i];

    return int_value;
};

